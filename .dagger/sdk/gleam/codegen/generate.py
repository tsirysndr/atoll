#!/usr/bin/env python3
"""Generate Gleam bindings from a Dagger GraphQL introspection JSON document.

Accepts a schema, {__schema: ...}, or {data: {__schema: ...}}. No third-party
Python dependencies. Generated modules share types to avoid import cycles.
"""
import argparse
import json
import re
import subprocess
import tempfile
from pathlib import Path

RESERVED = set('as assert case const delegate derive echo else fn if implement import let macro opaque panic pub test todo type use when'.split())
BASIC = {'String': 'String', 'Int': 'Int', 'Float': 'Float', 'Boolean': 'Bool', 'Void': 'Nil'}

def snake(name):
    name = re.sub(r'([A-Z]+)([A-Z][a-z])', r'\1_\2', name)
    name = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).lower().strip('_')
    return name + '_' if name in RESERVED else name

def pascal(name):
    return ''.join(x[:1].upper() + x[1:] for x in snake(name).split('_'))

def nonnull(ref):
    return ref['ofType'] if ref['kind'] == 'NON_NULL' else ref

def named(ref):
    while ref.get('ofType'):
        ref = ref['ofType']
    return ref

def docs(text):
    return '\n'.join(('/// ' + line).rstrip() for line in (text or '').splitlines()) + '\n' if text else ''

def expected(arg):
    for d in arg.get('directives', []):
        if d['name'] == 'expectedType':
            for a in d['args']:
                if a['name'] == 'name':
                    return json.loads(a['value'])
    n = named(arg['type'])['name']
    return n[:-2] if n.endswith('ID') else None

class Generator:
    def __init__(self, schema):
        self.schema = schema
        self.types = {t['name']: t for t in schema['types'] if not t['name'].startswith('_')}

    def typ(self, ref, nullable=True, prefix='types.', object_arg=None):
        if ref['kind'] == 'NON_NULL':
            return self.typ(ref['ofType'], False, prefix, object_arg)
        if ref['kind'] == 'LIST':
            value = 'List(' + self.typ(ref['ofType'], True, prefix, object_arg) + ')'
        elif object_arg:
            value = prefix + pascal(object_arg)
        else:
            value = BASIC.get(ref['name'], prefix + pascal(ref['name']))
        return 'Option(' + value + ')' if nullable else value

    def enc(self, ref, value, nullable=True, prefix='types.', object_arg=None):
        if ref['kind'] == 'NON_NULL':
            return self.enc(ref['ofType'], value, False, prefix, object_arg)
        if nullable:
            return f'query.optional({value}, fn(value) {{ {self.enc(ref, "value", False, prefix, object_arg)} }})'
        if ref['kind'] == 'LIST':
            return f'query.List(list.map({value}, fn(item) {{ {self.enc(ref["ofType"], "item", True, prefix, object_arg)} }}))'
        if object_arg:
            return f'query.Reference({value}.selection)'
        n = ref['name']
        if n in ['String','Int','Float','Boolean']:
            return f'query.{n}({value})'
        if n == 'Void': return 'query.Null'
        return f'{prefix}encode_{snake(n)}({value})'

    def reload(self, type_name, selection, id_value):
        if any(f['name'] == 'load' + type_name + 'FromID' for f in self.types[self.schema['queryType']['name']]['fields']):
            return f'query.root(query.connection({selection})) |> query.select("load{type_name}FromID", [#("id", query.String({id_value}))])'
        return f'query.load({selection}, "{type_name}", {id_value})'

    def dec(self, ref, selection='selection', nullable=True, id_object=None):
        if ref['kind'] == 'NON_NULL': return self.dec(ref['ofType'], selection, False, id_object)
        if ref['kind'] == 'LIST': value = 'decode.list(' + self.dec(ref['ofType'], selection, True, id_object) + ')'
        elif id_object or ref['kind'] in ['OBJECT', 'INTERFACE']:
            n = id_object or ref['name']
            source = 'decode.string' if id_object else 'decode.at(["id"], decode.string)'
            value = f'decode.map({source}, fn(id) {{ types.{pascal(n)}({self.reload(n, selection, "id")}) }})'
        else:
            n = ref['name']
            value = {'String':'decode.string','Int':'decode.int','Float':'decode.float','Boolean':'decode.bool','Void':'decode.map(decode.dynamic, fn(_) { Nil })'}.get(n, f'types.decode_{snake(n)}()')
        return f'decode.optional({value})' if nullable else value

    def generate(self, out):
        out.mkdir(parents=True, exist_ok=True)
        header = '//// Generated by codegen/generate.py. Do not edit.\n'
        ts = [header, 'import dagger/internal/query', 'import gleam/dynamic/decode', 'import gleam/list', 'import gleam/option.{type Option, None, Some}']
        for n,t in self.types.items():
            k=t['kind']; pn=pascal(n); sn=snake(n)
            ts.append(docs(t.get('description')))
            if k in ['OBJECT','INTERFACE']:
                ts.append(f'pub type {pn} {{ {pn}(selection: query.Selection) }}')
            elif k=='SCALAR' and n not in BASIC:
                ts += [f'pub type {pn} {{ {pn}(value: String) }}', f'pub fn encode_{sn}(value: {pn}) -> query.Value {{ query.String(value.value) }}', f'pub fn decode_{sn}() -> decode.Decoder({pn}) {{ decode.map(decode.string, {pn}) }}']
            elif k=='ENUM':
                variants = []
                used = set()
                for v in t['enumValues']:
                    name = pascal(v['name'])
                    if name in used: name += 'Alias'
                    if name in used: raise ValueError('Enum constructor collision: '+n)
                    used.add(name)
                    variants.append((v['name'], name))
                enum = [header, 'import dagger/internal/query', 'import gleam/dynamic/decode', docs(t.get('description'))]
                enum.append(f'pub type {pn} {{\n'+ '\n'.join(v for _,v in variants)+'\n}')
                enum.append(f'pub fn encode(value: {pn}) -> query.Value {{ query.Enum(case value {{\n'+'\n'.join(f'{v} -> "{raw}"' for raw,v in variants)+'\n}) }')
                enum.append(f'pub fn decoder() -> decode.Decoder({pn}) {{\n use value <- decode.then(decode.string)\n case value {{\n'+'\n'.join(f'"{raw}" -> decode.success({v})' for raw,v in variants)+f'\n _ -> decode.failure({variants[0][1]}, "{n}")\n }}\n }}')
                (out/(sn+'.gleam')).write_text('\n\n'.join(enum)+'\n')
                ts.insert(1, f'import dagger/{sn}')
                ts += [f'pub type {pn} = {sn}.{pn}', f'pub fn encode_{sn}(value: {pn}) -> query.Value {{ {sn}.encode(value) }}', f'pub fn decode_{sn}() -> decode.Decoder({pn}) {{ {sn}.decoder() }}']
            elif k=='INPUT_OBJECT':
                ts.append(f'pub type {pn} {{ {pn}('+', '.join(f'{snake(f["name"])}: {self.typ(f["type"],prefix="")}' for f in t['inputFields'])+') }')
                fields=[]
                for f in t['inputFields']:
                    v='value.'+snake(f['name']); enc=self.enc(f['type'],v,False,prefix='')
                    if f['type']['kind']=='NON_NULL': fields.append(f'[#("{f["name"]}", {enc})]')
                    else: fields.append(f'case {v} {{ None -> [] Some(item) -> [#("{f["name"]}", {self.enc(f["type"],"item",False,prefix="")})] }}')
                ts.append(f'pub fn encode_{sn}(value: {pn}) -> query.Value {{ query.Object(list.flatten(['+','.join(fields)+'])) }')
            elif k!='SCALAR': raise ValueError('Unsupported schema kind: '+k)
        (out/'types.gleam').write_text('\n\n'.join(ts)+'\n')
        count=0
        for n,t in self.types.items():
            if t['kind'] not in ['OBJECT','INTERFACE']:continue
            mod='client' if n==self.schema['queryType']['name'] else snake(n)
            lines=[header,'import dagger/internal/query','import dagger/types','import dagger/errors.{type Error as DaggerError}','import gleam/dynamic/decode','import gleam/list','import gleam/option.{type Option}']
            lines.append(f'pub type {pascal(n)} = types.{pascal(n)}')
            id_field = next((f for f in t['fields'] if f['name'] == 'id'), None)
            if id_field and n != self.schema['queryType']['name']:
                lines.append('/// Load an object by ID without executing a request.\n'+f'pub fn from_id(client: types.{pascal(self.schema["queryType"]["name"])}, id: {self.typ(id_field["type"], False)}) -> types.{pascal(n)} {{ types.{pascal(n)}({self.reload(n, "client.selection", "id.value")}) }}')
                lines.append('import dagger/mod/codec')
                id_constructor = pascal(named(id_field['type'])['name'])
                lines.append('/// Codec for passing this engine object to or from a Gleam Dagger module.\n'+f'pub fn codec() -> codec.Codec(types.{pascal(n)}) {{ codec.engine_object("{n}", fn(client, id) {{ from_id(client, types.{id_constructor}(id)) }}, fn(object) {{ object.selection }}) }}')
            for f in t['fields']:
                if f['name'].startswith('_') or named(f['type'])['name'].startswith('_'):continue
                count+=1
                req=[]; opts=[]
                for a in f['args']:
                    (req if a['type']['kind']=='NON_NULL' and a.get('defaultValue') is None else opts).append(a)
                fn=snake(f['name']); optname=pascal(f['name'])+'Option'
                def arg_obj(a):
                    e=expected(a)
                    return e if e in self.types and self.types[e]['kind'] in ['OBJECT','INTERFACE'] and not f['name'].startswith('load') else None
                params=[f'self: types.{pascal(n)}']+[f'{snake(a["name"])}: {self.typ(a["type"],False,object_arg=arg_obj(a))}' for a in req]
                ref=nonnull(f['type']); lazy=ref['kind'] in ['OBJECT','INTERFACE']
                output_object = expected(f)
                output_object = output_object if output_object in self.types and self.types[output_object]['kind'] in ['OBJECT', 'INTERFACE'] else None
                ret='types.'+pascal(ref['name']) if lazy else 'Result('+self.typ(f['type'], object_arg=output_object)+', DaggerError)'
                description=docs(f.get('description'))
                if f.get('isDeprecated'): description+=docs('Deprecated: '+(f.get('deprecationReason') or 'Deprecated by the engine.'))
                if opts:
                    lines.append(f'pub type {optname} {{\n'+'\n'.join(docs(a.get('description'))+pascal(f['name'])+pascal(a['name'])+'('+self.typ(a['type'],False,object_arg=arg_obj(a))+')' for a in opts)+'\n}')
                    lines.append(description+f'pub fn {fn}('+', '.join(params)+f') -> {ret} {{\n {fn}_with('+', '.join(['self']+[snake(a['name']) for a in req]+['[]'])+')\n}')
                    params.append('options: List('+optname+')')
                lines.append(description+f'pub fn {fn+"_with" if opts else fn}('+', '.join(params)+f') -> {ret} {{')
                arguments=[f'#("{a["name"]}", {self.enc(a["type"],snake(a["name"]),False,object_arg=arg_obj(a))})' for a in req]
                lines.append('let arguments = ['+', '.join(arguments)+']')
                if opts:
                    lines.append('let arguments = list.append(arguments, list.map(options, fn(option) { case option {')
                    lines.extend(pascal(f['name'])+pascal(a['name'])+f'(value) -> #("{a["name"]}", {self.enc(a["type"],"value",False,object_arg=arg_obj(a))})' for a in opts)
                    lines.append('} }))')
                lines.append(f'let selection = query.select(self.selection, "{f["name"]}", arguments)')
                if lazy: lines.append(f'types.{pascal(ref["name"])}(selection)')
                elif named(ref)['kind'] in ['OBJECT','INTERFACE']:
                    lines.append(f'query.execute_with_children(selection, "id", {self.dec(f["type"])})')
                else: lines.append(f'query.execute(selection, {self.dec(f["type"], id_object=output_object)})')
                lines.append('}')
            # Remove imports that generated module doesn't need (compiler also checks these).
            text='\n\n'.join(lines)+'\n'
            for imp,token in [('import dagger/errors.{type Error as DaggerError}','DaggerError)'),('import gleam/dynamic/decode','decode.'),('import gleam/list','list.'),('import gleam/option.{type Option}','Option(')]:
                if not re.search(r'(?<![A-Za-z_])'+re.escape(token), re.sub(r'///[^\n]*', '', text.replace(imp, ''))): text=text.replace(imp+'\n','')
            (out/(mod+'.gleam')).write_text(text)
        return count

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('schema',type=Path)
    parser.add_argument('--output',type=Path,default=Path(__file__).resolve().parents[1]/'src/dagger')
    args=parser.parse_args()
    schema=json.loads(args.schema.read_text())
    schema=schema.get('data',schema); schema=schema.get('__schema',schema)
    # Generate and format before replacing files; a bad schema leaves the SDK intact.
    with tempfile.TemporaryDirectory(prefix='dagger-gleam-codegen-') as temporary:
        staging = Path(temporary)
        count=Generator(schema).generate(staging)
        subprocess.run(['gleam', 'format', str(staging)], check=True)
        args.output.mkdir(parents=True, exist_ok=True)
        generated = {p.name for p in staging.glob('*.gleam')}
        for path in staging.glob('*.gleam'):
            target = args.output/path.name
            if target.exists() and not target.read_text().startswith('//// Generated by codegen/generate.py.'):
                raise ValueError('Refusing to overwrite handwritten module: '+str(target))
        for existing in args.output.glob('*.gleam'):
            if existing.name not in generated and existing.read_text().startswith('//// Generated by codegen/generate.py.'):
                existing.unlink()
        for path in staging.glob('*.gleam'):
            (args.output/path.name).write_text(path.read_text())
    print(f'Generated {count} fields from {args.schema}')

if __name__=='__main__': main()
