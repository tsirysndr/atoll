"""Regeneration and compatibility tests; run with Python's standard unittest."""
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATOR = ROOT / "codegen/generate.py"


class GeneratorTest(unittest.TestCase):
    def generate(self, schema, output):
        path = output.parent / "input.json"
        path.write_text(json.dumps(schema))
        return subprocess.run(
            [sys.executable, str(GENERATOR), str(path), "--output", str(output)],
            capture_output=True, text=True,
        )

    def test_checked_in_api_is_reproducible(self):
        schema = json.loads((ROOT / "codegen/schema.json").read_text())
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory) / "generated"
            result = self.generate({"data": {"__schema": schema}}, output)
            self.assertEqual(result.returncode, 0, result.stderr)
            for generated in output.glob("*.gleam"):
                self.assertEqual(generated.read_bytes(), (ROOT / "src/dagger" / generated.name).read_bytes(), generated.name)

    def test_old_style_ids_and_defaults(self):
        scalar = lambda name: {"kind": "SCALAR", "name": name}
        required = lambda ref: {"kind": "NON_NULL", "ofType": ref}
        field = lambda name, ref, args=[]: {"name": name, "type": ref, "args": args}
        schema = {"queryType": {"name": "Query"}, "types": [
            {"name": "Query", "kind": "OBJECT", "fields": [
                field("loadContainerFromID", required({"kind": "OBJECT", "name": "Container"}), [
                    {"name": "id", "type": required(scalar("ContainerID"))}
                ])
            ]},
            {"name": "ContainerID", "kind": "SCALAR"},
            {"name": "Container", "kind": "OBJECT", "fields": [
                field("id", required(scalar("ContainerID"))),
                field("stdout", required(scalar("String")), [
                    {"name": "trim", "type": required(scalar("Boolean")), "defaultValue": "false"}
                ]),
            ]},
            {"name": "String", "kind": "SCALAR"},
            {"name": "Boolean", "kind": "SCALAR"},
        ]}
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory) / "generated"
            result = self.generate({"__schema": schema}, output)
            self.assertEqual(result.returncode, 0, result.stderr)
            container = (output / "container.gleam").read_text()
            self.assertIn('"loadContainerFromID"', container)
            self.assertIn('id: types.ContainerId', container)
            self.assertIn('pub fn stdout(self: types.Container)', container)
            self.assertIn('StdoutTrim(Bool)', container)

    def test_regeneration_preserves_handwritten_files(self):
        schema = json.loads((ROOT / "codegen/schema.json").read_text())
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory) / "generated"
            output.mkdir()
            handwritten = output / "custom.gleam"
            handwritten.write_text('// Handwritten file\n')
            stale = output / "obsolete.gleam"
            stale.write_text('//// Generated by codegen/generate.py. Do not edit.\n')
            result = self.generate(schema, output)
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(handwritten.read_text(), '// Handwritten file\n')
            self.assertFalse(stale.exists())

    def test_collision_does_not_overwrite_handwritten_module(self):
        schema = json.loads((ROOT / "codegen/schema.json").read_text())
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory) / "generated"
            output.mkdir()
            handwritten = output / "container.gleam"
            handwritten.write_text('// My container\n')
            result = self.generate(schema, output)
            self.assertNotEqual(result.returncode, 0)
            self.assertEqual(handwritten.read_text(), '// My container\n')


if __name__ == "__main__":
    unittest.main()
